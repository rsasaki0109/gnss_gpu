function export_gsdc2023_taroz_gnss_state(result_gnss_path, phone_data_path, output_path)
%% Export Taroz fgo_gnss result state to a CSV that native parity tools can read.
% ``position_x/y/z`` are Taroz ENU coordinates, matching phone_data_imu_state.csv.
arguments
    result_gnss_path string
    phone_data_path string = ""
    output_path string = ""
end

if strlength(output_path) == 0
    [result_dir, ~, ~] = fileparts(result_gnss_path);
    output_path = fullfile(result_dir, "phone_data_gnss_state.csv");
end

if exist("setup_local_env", "file")
    setup_local_env();
end

load(result_gnss_path, "posest", "velest", "clkest", "dclkest");

n = posest.n;
epoch_index = (1:n)';
utcTimeMillis = epoch_index;
if strlength(phone_data_path) > 0
    load(phone_data_path, "obs");
    utcTimeMillis = obs.utcms(:);
end

clk = clkest;
if size(clk, 2) < 7
    clk = [clk zeros(size(clk, 1), 7 - size(clk, 2))];
end

origin_llh = repmat(posest.orgllh, n, 1);
origin_xyz = repmat(posest.orgxyz, n, 1);

state_table = table(epoch_index, utcTimeMillis, ...
    posest.enu(:, 1), posest.enu(:, 2), posest.enu(:, 3), ...
    posest.xyz(:, 1), posest.xyz(:, 2), posest.xyz(:, 3), ...
    posest.llh(:, 1), posest.llh(:, 2), posest.llh(:, 3), ...
    velest.enu(:, 1), velest.enu(:, 2), velest.enu(:, 3), ...
    velest.xyz(:, 1), velest.xyz(:, 2), velest.xyz(:, 3), ...
    clk(:, 1), clk(:, 2), clk(:, 3), clk(:, 4), clk(:, 5), clk(:, 6), clk(:, 7), ...
    dclkest(:), ...
    origin_llh(:, 1), origin_llh(:, 2), origin_llh(:, 3), ...
    origin_xyz(:, 1), origin_xyz(:, 2), origin_xyz(:, 3), ...
    'VariableNames', {'epoch_index', 'utcTimeMillis', ...
    'position_x', 'position_y', 'position_z', ...
    'ecef_x', 'ecef_y', 'ecef_z', ...
    'lat_deg', 'lon_deg', 'alt_m', ...
    'velocity_x', 'velocity_y', 'velocity_z', ...
    'velocity_ecef_x', 'velocity_ecef_y', 'velocity_ecef_z', ...
    'clock_bias_m_0', 'clock_bias_m_1', 'clock_bias_m_2', 'clock_bias_m_3', ...
    'clock_bias_m_4', 'clock_bias_m_5', 'clock_bias_m_6', ...
    'clock_drift_mps', ...
    'origin_lat_deg', 'origin_lon_deg', 'origin_alt_m', ...
    'origin_ecef_x', 'origin_ecef_y', 'origin_ecef_z'});

[output_dir, ~, ~] = fileparts(output_path);
if strlength(output_dir) > 0 && ~isfolder(output_dir)
    mkdir(output_dir);
end
writetable(state_table, output_path);
fprintf("wrote %s\n", output_path);
end
