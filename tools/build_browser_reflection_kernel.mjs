#!/usr/bin/env node
// Reproducible assembly only: the WAT fixes every floating-point operation.
import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {readFileSync,writeFileSync} from "node:fs";
import {dirname,resolve} from "node:path";
import {fileURLToPath} from "node:url";
import wabtFactory from "wabt";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const source=readFileSync(resolve(root,"tools/wasm/reflection-candidates.wat"),"utf8").replace(/\r\n/g,"\n");
const target=resolve(root,"docs/assets/simulation/reflection-candidates.bytes.mjs");
if(process.argv.slice(2).some(value=>value!=="--check"))throw new Error("Usage: node tools/build_browser_reflection_kernel.mjs [--check]");
assert.doesNotMatch(source,/\bf32\b|\bv128\b|\brelaxed\b/);
const wabt=await wabtFactory(),module=wabt.parseWat("reflection-candidates.wat",source,{simd:false,relaxed_simd:false});
try {
  module.resolveNames();module.validate();
  const {buffer}=module.toBinary({write_debug_names:false,canonicalize_lebs:true});
  const compiled=new WebAssembly.Module(buffer);
  assert.deepEqual(WebAssembly.Module.imports(compiled),[{module:"env",name:"memory",kind:"memory"}]);
  assert.deepEqual(WebAssembly.Module.exports(compiled),[{name:"scan",kind:"function"}]);
  const hash=createHash("sha256").update(source).digest("hex"),encoded=Buffer.from(buffer).toString("base64");
  const output='// Generated by tools/build_browser_reflection_kernel.mjs; edit the WAT source.\nexport const sourceSha256 = "'+hash+'";\nexport const encoded = "'+encoded+'";\n';
  if(process.argv.includes("--check"))assert.equal(readFileSync(target,"utf8").replace(/\r\n/g,"\n"),output,"Rebuild the browser reflection kernel");
  else writeFileSync(target,output);
  console.log((process.argv.includes("--check")?"Verified ":"Assembled ")+buffer.length+"-byte Float64 reflection kernel");
} finally {module.destroy();}
