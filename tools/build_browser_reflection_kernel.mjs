#!/usr/bin/env node
// Reproducible assembly only: the WAT fixes every floating-point operation.
import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {readFileSync,writeFileSync} from "node:fs";
import {dirname,resolve} from "node:path";
import {fileURLToPath} from "node:url";
import wabtFactory from "wabt";
import {expandReflectionSIMD} from "./wasm/reflection-variants.mjs";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
if(process.argv.slice(2).some(value=>value!=="--check"))throw new Error("Usage: node tools/build_browser_reflection_kernel.mjs [--check]");
const wabt=await wabtFactory();
for(const simd of [false,true]) {
  const name="reflection-candidates"+(simd?"-simd":"");
  const original=readFileSync(resolve(root,"tools/wasm/"+name+".wat"),"utf8").replace(/\r\n/g,"\n");
  const source=simd?expandReflectionSIMD(original):original;
  const target=resolve(root,"docs/assets/simulation/"+name+".bytes.mjs");
  assert.doesNotMatch(source,/\bf32|\b\w*relaxed\w*\b/);
  if(!simd)assert.doesNotMatch(source,/\bv128\b|\bf64x2\b/);
  const features={simd,relaxed_simd:false},module=wabt.parseWat(name+".wat",source,features);
  try {
    module.resolveNames();module.validate(features);
    const {buffer}=module.toBinary({write_debug_names:false,canonicalize_lebs:true});
    const compiled=new WebAssembly.Module(buffer);
    assert.deepEqual(WebAssembly.Module.imports(compiled),[{module:"env",name:"memory",kind:"memory"}]);
    assert.deepEqual(WebAssembly.Module.exports(compiled),[{name:"scan",kind:"function"}]);
    const hash=createHash("sha256").update(source).digest("hex"),encoded=Buffer.from(buffer).toString("base64");
    const output='// Generated by tools/build_browser_reflection_kernel.mjs; edit the WAT source or control-flow expander.\nexport const sourceSha256 = "'+hash+'";\nexport const encoded = "'+encoded+'";\n';
    if(process.argv.includes("--check"))assert.equal(readFileSync(target,"utf8").replace(/\r\n/g,"\n"),output,"Rebuild the browser reflection kernel");
    else writeFileSync(target,output);
    console.log((process.argv.includes("--check")?"Verified ":"Assembled ")+buffer.length+"-byte "+(simd?"SIMD ":"scalar ")+"Float64 reflection kernel");
  } finally {module.destroy();}
}
